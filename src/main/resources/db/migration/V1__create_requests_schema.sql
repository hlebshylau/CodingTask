CREATE SEQUENCE publication_id_seq START WITH 1000 INCREMENT BY 1;

CREATE TABLE requests (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255)                NOT NULL,
    body           VARCHAR(4000)               NOT NULL,
    status         VARCHAR(20)                 NOT NULL,
    publication_id BIGINT,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version        BIGINT                      NOT NULL,
    CONSTRAINT uk_requests_publication_id UNIQUE (publication_id),
    CONSTRAINT ck_requests_status CHECK (status IN ('CREATED', 'VERIFIED', 'ACCEPTED', 'PUBLISHED', 'REJECTED', 'DELETED')),
    CONSTRAINT ck_requests_publication CHECK ((status = 'PUBLISHED') = (publication_id IS NOT NULL))
);

CREATE INDEX idx_requests_status_created ON requests (status, created_at DESC, id DESC);
CREATE INDEX idx_requests_created ON requests (created_at DESC, id DESC);

CREATE TABLE request_audit (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      BIGINT                      NOT NULL,
    previous_status VARCHAR(20)                 NOT NULL,
    new_status      VARCHAR(20)                 NOT NULL,
    event           VARCHAR(20)                 NOT NULL,
    reason          VARCHAR(1000),
    performed_by    VARCHAR(100)                NOT NULL,
    occurred_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_request_audit_request FOREIGN KEY (request_id) REFERENCES requests (id)
);

CREATE INDEX idx_request_audit_request ON request_audit (request_id, occurred_at, id);
